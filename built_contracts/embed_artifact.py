#!/usr/bin/env python3
"""Generate a C++ TU embedding a contract artifact's bytes.

Used for artifacts that shipped libraries (test_ffi) must be able to load
without a hogd build tree or an installed contracts directory on disk. The
consumer registers the emitted array with
hogd::register_embedded_contract_artifact so contract_loader can serve it.
"""

import argparse
import pathlib


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("artifact", type=pathlib.Path)
    parser.add_argument("-n", "--name", required=True,
                        help="C identifier stem for the emitted symbols")
    parser.add_argument("-o", "--out", required=True, type=pathlib.Path,
                        help="output path for the .cc (a .h is emitted "
                             "alongside it)")
    args = parser.parse_args()

    data = args.artifact.read_bytes()
    name = args.name

    header = args.out.with_suffix(".h")
    header.write_text(
        "#pragma once\n"
        "\n"
        "#include <cstddef>\n"
        "\n"
        "namespace hogd::embedded {\n"
        f"extern const unsigned char {name}_artifact[];\n"
        f"extern const std::size_t {name}_artifact_len;\n"
        "} // namespace hogd::embedded\n"
    )

    lines = []
    for start in range(0, len(data), 12):
        chunk = data[start:start + 12]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    body = "\n".join(lines)

    args.out.write_text(
        "// Auto-generated by embed_artifact.py\n"
        "// DO NOT EDIT\n"
        "\n"
        # Including the header gives the namespace-scope const definitions
        # external linkage; without it they are internal and never exported.
        f'#include "{header.name}"\n'
        "\n"
        "#include <cstddef>\n"
        "\n"
        "namespace hogd::embedded {\n"
        f"const unsigned char {name}_artifact[] = {{\n"
        f"{body}\n"
        "};\n"
        f"const std::size_t {name}_artifact_len = sizeof({name}_artifact);\n"
        "} // namespace hogd::embedded\n"
    )


if __name__ == "__main__":
    main()
