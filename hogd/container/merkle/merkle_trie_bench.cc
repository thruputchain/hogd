constexpr size_t kNumKVPairs = 2'000'000;
constexpr size_t kLargeNumKVPairs = 20'000'000;
constexpr size_t kAdditionalPaths = 1'000;

// Generates a 64-byte path. Each path generated by this function is unique. The
// last 8 bytes of the path hold a counter value while the remaining bytes hold
// randomly generated values.
HexArray
generate_64_byte_path()
{
  constexpr size_t kPathNumBytes = 64;
  std::random_device rd;
  std::mt19937 gen(rd());

  static std::vector<std::byte> path(kPathNumBytes);
  static size_t counter = 0;
  std::uniform_int_distribution<int> path_dist(0, 0xff);
  memcpy(path.data() + path.size() - sizeof(counter), &counter,
         sizeof(counter));
  counter++;
  for (size_t i = 0; i < path.size() - sizeof(counter); i++) {
    path[i] = static_cast<std::byte>(path_dist(gen));
  }
  return HexArray(path);
}

std::vector<HexArray>
precompute_paths(size_t num_paths)
{
  std::vector<HexArray> paths;
  paths.reserve(num_paths);
  for (size_t i = 0; i < num_paths; i++) {
    paths.push_back(generate_64_byte_path());
  }
  return paths;
}

// Inserts 2 million KV pairs into a trie. Node hashes are computed on every
// insert operation.
void
insert_two_million(benchmark::State &state)
{
  MerkleTrie trie;

  std::vector<HexArray> paths = precompute_paths(/*num_paths=*/kNumKVPairs);
  for (auto _ : state) {
    for (const auto &path : paths) {
      CHECK(trie.insert(path, "hello"));
    }
  }
}
BENCHMARK(insert_two_million)->Iterations(1)->Unit(benchmark::kSecond);

// Inserts 2 million KV pairs into a trie. Node hashes are *not* computed on
// any insert operations. Rather, the hashes for all nodes are computed once
// after all 2 million KV pairs are inserted.
void
generate_all_hashes_two_million(benchmark::State &state)
{
  MerkleTrie trie;
  trie.set_should_hash_nodes_on_each_op(false);

  std::vector<HexArray> paths = precompute_paths(/*num_paths=*/kNumKVPairs);
  for (auto _ : state) {
    for (const auto &path : paths) {
      CHECK(trie.insert(path, "hello"));
    }
    trie.generate_all_hashes();
    trie.set_should_hash_nodes_on_each_op(true);
  }
}
BENCHMARK(generate_all_hashes_two_million)
    ->Iterations(1)
    ->Unit(benchmark::kSecond);

