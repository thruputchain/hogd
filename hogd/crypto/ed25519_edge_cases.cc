struct Iacr20201244TestVector {

  Iacr20201244TestVector(std::string_view message, std::string_view public_key,
                         std::string_view signature, bool should_fail)
    : message_(decode_hex(message)), should_fail_(should_fail)

  {
    auto pk = decode_hex(public_key);
    auto sig = decode_hex(signature);
    assert(pk.size() == 32);
    assert(sig.size() == 64);

    std::memcpy(public_key_.data(), pk.data(), 32);
    std::memcpy(signature_.data(), sig.data(), 64);
  }

  std::vector<std::byte> message_;
  Ed25519PublicKey public_key_;
  Ed25519Signature signature_;
  bool should_fail_;
};

