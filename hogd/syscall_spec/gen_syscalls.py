#!/bin/python3

import yaml

from yaml import CLoader as Loader, CDumper as Dumper

import argparse

syscall_argcount = 6

"""
Each syscall generates a
syscall_{callname}_inner(...); declaration.
The interface is typed, and not responsible for
e.g. validating OOB accesses for the input arguments.

Each syscall is specified in the following (example) format:
- name: "XYZ"
  needs_context: yes/no
  inputs:
    - list of inputs
  outputs:
    - list of outputs
  returns: yes/no (default: yes)
  syscall_return_type: typename 
    (default: HostFnStatus<SyscallErrorCode>; alternatively, HostFnResult)
  number: 0

Syscall yaml specification is as follows.

name:
  type: string
  required: yes
  description: The name of the syscall.

needs_context:
  type: boolean (yes/no)
  required: yes
  description: Defines whether or not a SyscallHandler& reference is passed
  to the syscall.  Most syscalls will have this as a yes; there are
  a few (i.e. SHA256) where this is not required.

needs_gas:
  type: boolean
  required: no
  description: Whether or not the amount of currently available gas
  should be passed as input to the syscall.
  default: no
  
returns:
  type: boolean
  required: no
    default: no
  description: Defines whether or not the function returns to the caller
  or terminates the caller runtime instance.

syscall_return_type:
  type: HostFnStatus<SyscallErrorCode> or HostFnResult
  required: no
    default: HostFnStatus<SyscallErrorCode>
  description: syscall_return_type is the type of the object returned by the 
  syscall.  Most syscalls can return a HostFnStatus<SyscallErrorCode>; 
  however, some syscalls need to explicitly terminate the runtime (without 
  forcing an error, or with a specific error code: e.g the RETURN syscall).
  The HostFnResult object contains that extra data.  Inside the autogenerated 
  code,functions that return HostFnStatus<SyscallErrorCode> are converted to 
  returning a HostFnResult. HostFnResult is returned by the outer syscall.

inputs and outputs are lists of parameters, of the following yaml type.
The inputs and outputs are lists of parameters.
The logic is largely the same, except that inputs are const and outputs are not,
and variables are named input_{name} or output_{name} appropriately.

name:
  type: string
  required: yes
  description: Name of the argument (either input_{name} or output_{name}).

typename: string
  required: no
    default: none
  description: The type of the supplied argument.  Must be a trivially copyable
  type.  `typename` must be present in both the syscall code (e.g., an XDR type,
  or a basic type) and be present in contract code.  For types that have 
  different names, the optional `rust_typename` parameter may be set.

primitive_type: bool
  required: no
    default: no
  description: If the trivially copyable type is a primitive type that can
  fit within a uint64_t, then this argument will be passed by value
  as one of the arguments to the syscall, instead of as an offset into contract 
  memory.

  Only available for input arguments.

rust_typename: string
  required: no
    default: the value set in typename
  description: Used when rust names a type differently from the C++ code
  in the syscall.

optional: bool
  required: no
    default: no

  description: This syscall argument is optional.  
  Passed to syscall_{name}_inner as a pointer, instead of a reference.

  Not available with primitive_type = yes.

span_argument: bool
  required: no
    default: no
  description: The argument is a bytestring (a span) into contract memory.
  Passed into c++ as a std::span<{const}std::byte>.

  Mutually exclusive with typename or primitive_type.

custom_parsing: bool
  required: no
    default: no
  description: Some input argument types require parsing in ways that don't 
  quite fit into one of the above options. These we support with a custom 
  parsing option.

custom_args_required: int
  required: only if custom_parsing is true
  description: The number of arguments passed to the custom parsing handler.
"""

"""
Generate the declaration details for one syscall input or output

Return format:
local_user_arg_count, inner_arg_decl

local_user_args_count is the number of uint64_t syscall inputs
consumed by this argument.  Used only in internal assertions.

inner_arg_decl is the parameter of the inner syscall declaration corresponding 
to this argument.
"""
def gen_validate_arg(inp, *, is_input):
  arg_name = inp["name"]
  const = ""
  in_out = "output"
  if (is_input):
    const = "const "
    in_out = "input"

  optional = False
  if "optional" in inp and inp["optional"]:
    optional = True

  if "span_argument" in inp and inp["span_argument"]:
    arg_name = f"{in_out}_{arg_name}"
    if optional:
      return 2, f"std::optional<std::span<{const}std::byte>> {arg_name}"
    else:
      return 2, f"std::span<{const}std::byte> {arg_name}"
  # endif span_argument

  typename = inp["typename"]
  arg_name = f"{in_out}_{arg_name}"

  # put optional_ on front of arg name, for readability
  if optional:
    arg_name = f"optional_{arg_name}"
  
  if "primitive_type" in inp and inp["primitive_type"] and is_input:
    if optional:
      raise Exception("optional primitive_type is unimplemented");
    return 1, f"{typename} {arg_name}"

  if "custom_parsing" in inp and inp["custom_parsing"] and is_input:
    if optional:
      raise Exception("optional parsing is a strict subset of custom parsing--don't use both")
    num_args = inp["custom_args_required"]

    return num_args, f"{const}{typename}& {arg_name}"
  #endif custom_parsing

  if optional:
    return 1, f"{const}{typename}* {arg_name}"
  # end optional arg

  # else fixed size
  return 1, f"{const}{typename}& {arg_name}"


def gen_inner_outer(syscall):
  name = syscall["name"]

  user_arg_count = 0
  inner_arg_decl_strs = []

  syscall_handler_decl = ""
  inner_return_type = "HostFnStatus<SyscallErrorCode>"

  if "syscall_return_type" in syscall:
    inner_return_type = syscall["syscall_return_type"]

  if syscall["inputs"] is not None:
    for arg in syscall["inputs"]:
      local_user_arg_count, inner_arg_decl = gen_validate_arg(arg, is_input = True)
      user_arg_count += local_user_arg_count
      inner_arg_decl_strs.append(inner_arg_decl)

  if syscall["outputs"] is not None:
    for arg in syscall["outputs"]:
      local_user_arg_count, inner_arg_decl  = gen_validate_arg(arg, is_input = False)
      user_arg_count += local_user_arg_count
      inner_arg_decl_strs.append(inner_arg_decl)

  if user_arg_count > syscall_argcount:
    raise ValueError("too many syscall args")
  
  if "needs_gas" in syscall and syscall["needs_gas"]:
    inner_arg_decl_strs = ["WrappedGasAmount remaining_gas"] + inner_arg_decl_strs

  if syscall["needs_context"]:
    inner_arg_decl_strs = ["SystemCallHandler& syscall_handler"] + inner_arg_decl_strs

  inner_arg_decls = ", ".join(inner_arg_decl_strs);

  inner = f"""std::pair<{inner_return_type}, GasAmount>
syscall_{name}_inner({syscall_handler_decl}{inner_arg_decls});

"""
  frame = f"""std::pair<{inner_return_type}, GasAmount>
syscall_{name}_inner({syscall_handler_decl}{inner_arg_decls})
{{
  throw std::runtime_error("unimplemented");
}}

"""
  return inner, frame

def gen_inner(syscall):
  return gen_inner_outer(syscall)[0]

def gen_frame(syscall):
  return gen_inner_outer(syscall)[1]


def gen_syscall_table_entry(syscall):
  name = syscall["name"]
  return f"""    std::pair{{SyscallNo::k{name}, &wrap_outer<SyscallNo::k{name}, &syscall_{name}_inner>}},
"""

def gen_syscall_table(spec):
  counter = 0
  max_seen = -1
  syscall_map = {}
  for syscall in spec:
    number = syscall["number"]
    if (number >= max_seen):
      max_seen = number + 1
    syscall_map[number] = syscall

  if max_seen != len(syscall_map):
    raise Exception("SyscallNo Gap!")
  table = f"""constexpr static std::array<std::pair<SyscallNo, SyscallFunc>, {max_seen}> kSyscallTable = {{
"""
  for i in range(0, max_seen):
    table += gen_syscall_table_entry(syscall_map[i])
  table += "};"
  return table

def gen_syscall_inner_h(spec):
  inner_decls=""

  for syscall in spec:
    inner_decls += gen_inner(syscall)

    syscall_table = gen_syscall_table(spec)

  return f"""// -*-C++-*-

// *** Generated Code  ***
// *** Do not check in ***

#pragma once

#include <array>
#include <utility>

#include "hogd/base/types.h"
#include "hogd/hogexec/runtime/status.h"
#include "hogd/hogexec/runtime/syscall_entry_outer.h"
#include "syscall.hh"
#include "types.hh"

namespace hogd {{

class SystemCallHandler;
class Runtime;

{inner_decls}

using SyscallFunc = std::pair<HostFnResult, uint64_t> (*)(
    SystemCallHandler&, Runtime&, {", ".join(["uint64_t"] * (syscall_argcount))});

{syscall_table}

}}// namespace hogd
"""

def gen_syscall_io_arg_decl(arg):
  end_decorator = ""
  argtype = ""
  if "xdr_typename" in arg:
    argtype = arg["xdr_typename"]
  elif "span_argument" in arg and arg["span_argument"]:
    argtype = "opaque"
    end_decorator = "<>"
  else:
    argtype = arg["typename"]

  pointerdecl = ""
  if "optional" in arg and arg["optional"]:
    pointerdecl = "*"
  argname = arg["name"]
  return f"  {argtype} {pointerdecl}{argname}{end_decorator};"

def gen_syscall_input_arg_xdr(syscall):
  name = syscall["name"]
  decls = []

  if syscall["inputs"] is not None:
    for arg in syscall["inputs"]:
      decl = gen_syscall_io_arg_decl(arg)
      decls = decls + [decl]
  if len(decls) == 0:
    decls = ["  void;"]
  decls_joined = "\n".join(decls)

  return f"""struct {name}_input {{
{decls_joined}
}};

""", f"""  case k{name}:
    {name}_input {name};
"""

def gen_syscall_output_arg_xdr(syscall):
  name = syscall["name"]
  decls = []

  if syscall["outputs"] is not None:
    for arg in syscall["outputs"]:
      decl = gen_syscall_io_arg_decl(arg)
      decls = decls + [decl]
  if len(decls) == 0:
    decls = ["  void;"]
  decls_joined = "\n".join(decls)

  return f"""struct {name}_output {{
{decls_joined}
}};

""", f"""  case k{name}:
    {name}_output {name};
"""

def gen_syscall_arg_xdr(spec):
  structs = ""
  decls_in = ""
  decls_out = ""
  for call in spec["syscalls"]:
    struct, decl = gen_syscall_input_arg_xdr(call)
    structs += struct
    decls_in += decl
    struct, decl = gen_syscall_output_arg_xdr(call)
    structs += struct
    decls_out += decl

  return f"""// clang-format off
%#include "types.hh"
%#include "syscall.hh"

namespace hogd {{
  // clang-format on
{structs}

union SyscallInput switch(SyscallNo syscall) {{
{decls_in}
}};

union SyscallOutput switch(SyscallNo syscall) {{
{decls_out}
}};

}}

"""


def gen_syscall_x(spec_full):
  spec = spec_full["syscalls"]
  syscalls = {}
  errors = {}
  for syscall in spec:
    syscalls[syscall["number"]]=syscall["name"]

  enumdecls = ""

  for i in range(0, len(syscalls)):
    name = syscalls[i]
    enumdecls += f"    k{name} = {i},\n"

  error_spec = spec_full["errors"]

  for error in error_spec:
    errors[error["number"]]=error

  error_enumdecls = ""

  for num in errors.keys():
    name = errors[num]["name"]
    docstring=errors[num]["doc"]
    error_enumdecls += f"\n    // {docstring}\n    k{name} = {num},\n"


  return f"""// clang-format off
%// *** Generated Code  ***
%// *** Do not check in ***

%#include "types.hh"

namespace hogd {{
// clang-format on

enum SyscallNo {{
{enumdecls}}};

enum SyscallErrorCode {{{error_enumdecls}}};

}} // namespace hogd
"""



"""
Generate rust bindings for each syscall.
Binding code depends on a (defined in a separate, not autogenerated file)
extern function definition.

This code generates two functions for each syscall.
One is a `uninit_{name}` function,
which takes MaybeUninit arguments for the output variables,
and one `raw_{name}` that does not 
(and is largely a wrapper around the uninit() variant).
"""
def gen_rs_syscall_binding(syscall):
  name = syscall["name"]
  inputdecls = []
  syscallargs = []
  uninit_args = []
  if syscall["inputs"] is not None:
    for inp in syscall["inputs"]:

      optional = False
      if "optional" in inp and inp["optional"]:
        optional = True

      input_name = inp["name"]
      input_type = "[u8]"
      if "primitive_type" in inp and inp["primitive_type"]:
        input_type = inp["typename"]
        if "rust_typename" in inp:
          input_type = inp["rust_typename"]
        syscallargs.append(f"""{input_name} as u64""")
        inputdecls.append(f"""{input_name} : {input_type}""")
        uninit_args.append(f"""{input_name}""")
      elif "custom_parsing" in inp and inp["custom_parsing"]:
        # custom parsing, for now I just implement as a direct passthrough
        # and assume the sdk wrapper will handle.  Input types are just u64s
        for i in range(0, inp["custom_args_required"]):
          syscallargs.append(f"""{input_name}_{i}""")
          inputdecls.append(f"""{input_name}_{i} : u64""")
          uninit_args.append(f"""{input_name}_{i}""")
      elif "typename" in inp:
        #Fixed size arguments
        input_type = inp["typename"]
        if "rust_typename" in inp:
          input_type = inp["rust_typename"]
        if optional:
          syscallargs.append(f"""match {input_name} {{ Some(x) => {{x.as_ptr() as u64 }}, None => u64::MAX }}""")
          inputdecls.append(f"""{input_name} : Option<&{input_type}>""")
          uninit_args.append(f"""{input_name}""")
        else:
          syscallargs.append(f"""{input_name}.as_ptr() as u64""")
          inputdecls.append(f"""{input_name} : &{input_type}""")
          uninit_args.append(f"""{input_name}""")
      
      else: # span argument
        if "span_argument" not in inp or not inp["span_argument"]:
          raise Exception("unknown argument type")

        if optional:
          syscallargs.append(f"""match {input_name} {{ Some(x) => {{x.as_ptr() as u64 }}, None => u64::MAX }}""")
          syscallargs.append(f"""match {input_name} {{ Some(x) => {{x.len() as u64 }}, None => 0 }}""")
          inputdecls.append(f"""{input_name} : Option<&{input_type}>""")
          uninit_args.append(f"""{input_name}""")
        else:
          syscallargs.append(f"""{input_name}.as_ptr() as u64""")
          syscallargs.append(f"""{input_name}.len() as u64""")
          inputdecls.append(f"""{input_name} : &{input_type}""")
          uninit_args.append(f"""{input_name}""")

  outputargs = []
  outputdecls = []
  outputinits = []

  uninit_inputdecls = list(inputdecls)

  if syscall["outputs"] is not None:
    for outp in syscall["outputs"]:
      output_name = outp["name"]
      output_type = "[u8]"
      uninit_outputtype = "[MaybeUninit<u8>]"

      if "optional" in outp and outp["optional"]:
        raise Exception("optional outputs not supported")
      if "custom_parsing" in outp and outp["custom_parsing"]:
        raise Exception("custom parsing outputs not supported")

      if "primitive_type" in outp and outp["primitive_type"]:
        output_type = outp["typename"]
        if "rust_typename" in outp:
          output_type = outp["rust_typename"]
        syscallargs.append(f"""to_offset_mut({output_name}) as u64""")
        uninit_outputtype = output_type
        uninit_args.append(f"""{output_name}""")
      elif "typename" in outp:
        # Fixed-size arguments
        output_type = outp["typename"]
        if "rust_typename" in outp:
          output_type = outp["rust_typename"]
        uninit_outputtype = f"""MaybeUninit<{output_type}>"""
        syscallargs.append(f"""{output_name}.as_mut_ptr() as u64""")
        uninit_args.append(f"""unsafe {{core::mem::transmute({output_name})}}""")
      else:
        #span argument
        if "span_argument" not in outp or not outp["span_argument"]:
          raise Exception("unknown output type")
        syscallargs.append(f"""{output_name}.as_mut_ptr() as u64""")
        syscallargs.append(f"""{output_name}.len() as u64""")
        uninit_args.append(f"""unsafe {{core::mem::transmute({output_name})}}""")

      inputdecls.append(f"""{output_name} : &mut {output_type}""")
      uninit_inputdecls.append(f"""{output_name} : &mut {uninit_outputtype}""")

  inputdecl_str = ", ".join(inputdecls)
  uninit_inputdecl_str = ", ".join(uninit_inputdecls)

  if len(syscallargs) < syscall_argcount:
    syscallargs += ["0"] * (syscall_argcount - len(syscallargs))

  syscallargs_str = """,
            """.join(syscallargs)

  uninit_args_str = ", ".join(uninit_args)
  
  syscall_return_type = "Result<(), i32>"

  errdecl = "let err = "
  errhandle_str = """if err != SyscallErrorCode::kNone as i32 {
        return Err(err);
    }

    Ok(())"""

  if "returns" in syscall and not syscall["returns"]:
    syscall_return_type = "!"
    errhandle_str = "unsafe {unreachable_unchecked()}"
    errdecl = ""

  return f"""pub fn uninit_{name}({uninit_inputdecl_str}) -> {syscall_return_type} {{

    // syscall will initialize outputs, if error is kNone
    {errdecl}
        syscall_wrapper(SyscallNo::k{name},
            {syscallargs_str});

    {errhandle_str}
}}

pub fn raw_{name}({inputdecl_str}) -> {syscall_return_type} {{
    uninit_{name}({uninit_args_str})
}}

"""

def gen_rs_syscall_bindings(spec):
  syscall_str = ""
  for syscall in spec:
    syscall_str += gen_rs_syscall_binding(syscall)

  return f"""// -*-Rust-*-

// *** Generated Code  ***
// *** Do not check in ***

#![allow(non_snake_case)]
use rs_xdr::*;
use crate::syscall::{{syscall_wrapper, to_offset_mut}};
use core::mem::MaybeUninit;
use core::hint::unreachable_unchecked;

{syscall_str}

"""

def gen_syscall_frame(spec, args):
  req_calls = []
  for arg in args:
    for call in spec:
      if (call["number"] == arg):
        frame = gen_frame(call)
        req_calls.append(frame)

  joined = "".join(req_calls)

  return f"""#include "hogd/hogexec/runtime/syscall_inner.h"

#include <cstddef>
#include <span>
#include <utility>

#include "hogd/hogexec/runtime/status.h"
#include "hogd/hogexec/runtime/syscall_handler.h"
#include "syscall.hh"
#include "types.hh"

namespace hogd {{

{joined}
}}"""

parser = argparse.ArgumentParser(description="syscall generator")

parser.add_argument(
  '--syscall_x', 
  action='store_true', 
  help="gen syscall.x")
parser.add_argument(
  '--syscall_args_x', 
  action='store_true', 
  help="gen syscall_args.x")
parser.add_argument(
  '--syscall_inner_h', 
  action='store_true', 
  help="gen syscall_inner.h")
parser.add_argument(
  '--syscall_yaml', 
  type=str, 
  required = True, 
  help = "input yaml")
parser.add_argument(
  '--syscall_rs', 
  action='store_true', 
  help = 'gen rust syscall bindings')
parser.add_argument(
  '--output_dir', 
  type=str, 
  default = ".", 
  help = "output folder")
parser.add_argument(
  '--syscall_frame', 
  nargs='+', 
  type=int, 
  help = "syscall nos")

args = parser.parse_args()

spec_full = yaml.load(open(args.syscall_yaml, 'r').read(), Loader=Loader)
spec = spec_full["syscalls"]

if (args.syscall_x):
  filename = args.output_dir + "/syscall.x"
  with open(filename, "w") as f:
    f.write(gen_syscall_x(spec_full))

if (args.syscall_args_x):
  filename = args.output_dir + "/syscall_args.x"
  with open(filename, "w") as f:
    f.write(gen_syscall_arg_xdr(spec_full))

if (args.syscall_inner_h):
  filename = args.output_dir + "/syscall_inner.h"
  with open(filename, "w") as f:
    f.write(gen_syscall_inner_h(spec))

if (args.syscall_rs):
  filename = args.output_dir + "/syscall_bindings.rs"
  with open(filename, "w") as f:
    f.write(gen_rs_syscall_bindings(spec))

if (args.syscall_frame is not None and len(args.syscall_frame) > 0):
  print(gen_syscall_frame(spec, args.syscall_frame))

