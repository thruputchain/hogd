#!/bin/bash

# This script syncs release artifacts from a GitHub repository to a local directory.
# It uses the GitHub API to fetch release information and download assets.

# Exit immediately if a command exits with a non-zero status.
set -e

# --- Configuration (from Environment Variables) ---
# This script is configured via environment variables.
#
# GITHUB_TOKEN: Required. A GitHub PAT with "repo" scope.

: "${GITHUB_TOKEN:?Error: GITHUB_TOKEN environment variable is not set.}"

REPOSITORY="groundhogchain/hogd"
MIRROR_PATH="/home/hog12/www/builds/test-ffi"
# --- End of Configuration ---

# --- Prerequisite Check ---
# This script requires `jq` to parse JSON from the GitHub API.
if ! command -v jq &>/dev/null; then
  echo "Error: jq is not installed." >&2
  echo "Please install jq to use this script. (e.g., 'brew install jq' or 'sudo apt-get install jq')" >&2
  exit 1
fi
# --- End of Prerequisite Check ---

echo "Starting GitHub release artifact sync for $REPOSITORY"

# 1. Create the base mirror directory if it doesn't already exist.
mkdir -p "$MIRROR_PATH"

# 2. Get the list of all releases from the GitHub API.
echo "Fetching list of releases from GitHub API..."
RELEASES_JSON=$(curl -s -L \
  -H "Accept: application/vnd.github+json" \
  -H "Authorization: Bearer $GITHUB_TOKEN" \
  -H "X-GitHub-Api-Version: 2022-11-28" \
  "https://api.github.com/repos/$REPOSITORY/releases")

# If the response is empty or contains an error, exit.
if [ -z "$RELEASES_JSON" ] || echo "$RELEASES_JSON" | jq -e '.message' >/dev/null; then
  echo "Error: Failed to fetch releases. Response from GitHub API:" >&2
  echo "$RELEASES_JSON" >&2
  exit 1
fi

# 3. Loop through each release object returned by the API.
echo "Checking for new releases to mirror..."
echo "$RELEASES_JSON" | jq -c '.[]' | while read -r release; do
  TAG_NAME=$(echo "$release" | jq -r '.tag_name')
  RELEASE_PATH="$MIRROR_PATH/$TAG_NAME"
  ASSETS_JSON=$(echo "$release" | jq '.assets')

  echo "Processing release: '$TAG_NAME'"
  echo "Release path: '$RELEASE_PATH'"

  # Ensure the local directory for this release exists.
  mkdir -p "$RELEASE_PATH"

  # 5. For the new release, loop through each asset to find .tar.gz archives.
  echo "$ASSETS_JSON" | jq -c '.[]' | while read -r asset; do
    ASSET_NAME=$(echo "$asset" | jq -r '.name')

    # Rule: Skip source code tarballs (these are auto-generated by GitHub)
    if [[ "$ASSET_NAME" == "source.tar.gz" || "$ASSET_NAME" == "source.zip" ]]; then
      echo "--> Skipping source tarball: $ASSET_NAME"
      continue
    fi

    # Process only the asset tarballs, not the checksum files or others.
    if [[ "$ASSET_NAME" != *.tar.gz ]]; then
      continue
    fi

    TAR_ASSET_URL=$(echo "$asset" | jq -r '.url')
    LOCAL_TAR_PATH="$RELEASE_PATH/$ASSET_NAME"

    # Find the corresponding .sha256 file's URL for this asset.
    SHA_ASSET_URL=$(echo "$ASSETS_JSON" | jq -r ".[] | select(.name == \"${ASSET_NAME}.sha256\") | .url")

    if [ -z "$SHA_ASSET_URL" ]; then
      echo "--> WARNING: No .sha256 file found for '$ASSET_NAME'. Cannot verify. Skipping."
      continue
    fi

    echo "--> Verifying asset: $ASSET_NAME"

    # 1. Get the official checksum from the .sha256 file on GitHub.
    # The `tr -d '\r'` handles potential CRLF line endings.
    REMOTE_CHECKSUM=$(curl -s -L -H "Authorization: Bearer $GITHUB_TOKEN" -H "Accept: application/octet-stream" "$SHA_ASSET_URL" | awk '{print $1}' | tr -d '\r')

    # Save the checksum file next to the binary (always overwrite).
    CHECKSUM_FILE="$LOCAL_TAR_PATH.sha256"
    echo "$REMOTE_CHECKSUM" >"$CHECKSUM_FILE"
    echo "    Saved checksum to '$CHECKSUM_FILE'"

    NEEDS_DOWNLOAD=false
    # 2. Check if the .tar.gz file exists locally and if its checksum matches.
    if [ -f "$LOCAL_TAR_PATH" ]; then
      LOCAL_CHECKSUM=$(sha256sum "$LOCAL_TAR_PATH" | awk '{print $1}')
      if [ "$REMOTE_CHECKSUM" == "$LOCAL_CHECKSUM" ]; then
        echo "    Checksum OK. '$ASSET_NAME' is up to date."
      else
        echo "    Checksum mismatch for '$ASSET_NAME'. Re-downloading."
        NEEDS_DOWNLOAD=true
      fi
    else
      echo "    '$ASSET_NAME' not found locally. Downloading."
      NEEDS_DOWNLOAD=true
    fi

    # 3. Download the .tar.gz file if necessary.
    if [ "$NEEDS_DOWNLOAD" = true ]; then
      echo "    Downloading '$ASSET_NAME'..."
      curl -s -L \
        -H "Accept: application/octet-stream" \
        -H "Authorization: Bearer $GITHUB_TOKEN" \
        -H "X-GitHub-Api-Version: 2022-11-28" \
        -o "$LOCAL_TAR_PATH" \
        "$TAR_ASSET_URL"

      # 4. Verify the checksum of the newly downloaded file.
      NEW_LOCAL_CHECKSUM=$(sha256sum "$LOCAL_TAR_PATH" | awk '{print $1}')
      if [ "$REMOTE_CHECKSUM" == "$NEW_LOCAL_CHECKSUM" ]; then
        echo "    Download successful and verified."
      else
        echo "    ERROR: Checksum mismatch after download for '$ASSET_NAME'!" >&2
        # Clean up the corrupted file.
        rm "$LOCAL_TAR_PATH"
      fi
    fi
  done
done

echo "GitHub release artifact sync complete."
